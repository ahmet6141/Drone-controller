def kulfan(name: str, P: np.ndarray):
    import aerosandbox as asb
    af = asb.Airfoil(name=name, coordinates=P)
    kaf = af.to_kulfan_airfoil()
    fu0, fl0 = _surfaces(np.asarray(af.coordinates))
    fu1, fl1 = _surfaces(np.asarray(kaf.to_airfoil().coordinates))
    xs = np.linspace(0.005, 0.995, 199)
    err = max(np.max(np.abs(fu0(xs) - fu1(xs))), np.max(np.abs(fl0(xs) - fl1(xs))))
    return kaf, float(err)


def polar(kaf, Re: float, case: str, model: str = MODEL) -> dict:
    import neuralfoil as nf
    r = nf.get_aero_from_kulfan_parameters(kaf.kulfan_parameters, alpha=ALPHA, Re=Re, model_size=model, **CASES[case])
    return {k: np.asarray(r[k], float) for k in ("CL", "CD", "CM", "Top_Xtr", "Bot_Xtr", "analysis_confidence")}


def _r(v, n=4):
    return None if v is None or not np.isfinite(v) else round(float(v), n)


def metrics(p: dict) -> dict:
    a, cl, cd, cm = ALPHA, p["CL"], p["CD"], p["CM"]
    i_max = int(np.argmax(cl))
    task = a <= ALPHA_TASK_MAX
    i_task = int(np.argmax(np.where(task, cl, -9.0)))
    i_min = int(np.argmin(np.where(task, cd, 9.0)))
    lim = BUCKET_FACTOR * cd[i_min]
    lo = i_min
    while lo > 0 and cd[lo - 1] <= lim:
        lo -= 1
    hi = i_min
    while hi < len(a) - 1 and cd[hi + 1] <= lim and a[hi + 1] <= ALPHA_TASK_MAX:
        hi += 1
    br = slice(0, i_max + 1)                        # pre-stall branch for cl-based interpolation
    clb = cl[br]
    order = np.argsort(clb)

    def at_cl(arr, c):
        if c < clb.min() or c > clb.max():
            return None
        return float(np.interp(c, clb[order], arr[br][order]))

    ld = np.where(task, cl / cd, -1e9)
    i_ld = int(np.argmax(ld))
    e = np.where(task & (cl > 0), np.abs(cl) ** 1.5 / cd, 0.0)
    i_e = int(np.argmax(e))
    lin = (a >= -2.0) & (a <= 4.0)
    slope, icpt = np.polyfit(a[lin], cl[lin], 1)
    cd06, cd09 = at_cl(cd, CL_CRUISE), at_cl(cd, CL_LOITER)
    post = None
    if a[i_max] + 3.0 <= a[-1]:
        post = float(np.interp(a[i_max] + 3.0, a, cl)) / float(cl[i_max])
    return {
        "cl_max": _r(cl[i_max], 3),
        "alpha_cl_max_deg": _r(a[i_max], 2),
        "cl_max_beyond_22deg": bool(i_max >= len(a) - 1),
        "cl_max_within_alpha_m4_16deg": _r(cl[i_task], 3),
        "cd_min": _r(cd[i_min], 5),
        "cl_at_cd_min": _r(cl[i_min], 3),
        "drag_bucket_cl_range": [_r(cl[lo], 3), _r(cl[hi], 3)],
        "cl_alpha_per_deg": _r(slope, 4),
        "alpha_zero_lift_deg": _r(-icpt / slope, 2),
        "cm_c4_at_cl_cruise": _r(at_cl(cm, CL_CRUISE), 4),
        "cm_c4_at_cl_loiter": _r(at_cl(cm, CL_LOITER), 4),
        "cd_at_cl_cruise": _r(cd06, 5),
        "cd_at_cl_loiter": _r(cd09, 5),
        "cd_at_cl_1p1": _r(at_cl(cd, 1.1), 5),
        "cd_at_cl_1p3": _r(at_cl(cd, 1.3), 5),
        "l_over_d_at_cl_cruise": _r(CL_CRUISE / cd06, 1) if cd06 else None,
        "l_over_d_at_cl_loiter": _r(CL_LOITER / cd09, 1) if cd09 else None,
        "l_over_d_max": _r(ld[i_ld], 1),
        "cl_at_l_over_d_max": _r(cl[i_ld], 3),
        "endurance_cl15_over_cd_max": _r(e[i_e], 1),
        "cl_at_endurance_max": _r(cl[i_e], 3),
        "xtr_upper_at_cl_cruise": _r(at_cl(p["Top_Xtr"], CL_CRUISE), 3),
        "xtr_lower_at_cl_cruise": _r(at_cl(p["Bot_Xtr"], CL_CRUISE), 3),
        "post_stall_cl_ratio_at_alpha_clmax_plus3deg": _r(post, 3),
        "analysis_confidence_min_prestall": _r(p["analysis_confidence"][br].min(), 3),
    }


def _rekey(Re):
    return f"Re_{Re / 1e6:g}e6"


def run_airfoils() -> dict:
    out = {}
    for group, items, res in (("wing", WING, RE_WING), ("tail", TAIL, RE_TAIL)):
        for file, name, src, why in items:
            title, P = load(file, src)
            g = geometry(P)
            kaf, fit_err = kulfan(name, P)
            entry = {"name": name, "group": group, "tag": "estimate", "source": NF_URL, "coordinate_source": src,
                     "file": f"ucav250/data/airfoils/{file}.dat" if src == "uiuc" else None,
                     "uiuc_url": f"{UIUC_URL}{file}.dat", "title": title, "why_included": why,
                     "geometry": g, "gault_stall_type_Re_1_3e6": gault_stall_type(g["y_upper_at_x0p0125_percent_c"]),
                     "kulfan_fit_max_dy_over_c": round(fit_err, 5), "polars": {}}
            for case in CASES:
                entry["polars"][case] = {_rekey(Re): metrics(polar(kaf, Re, case)) for Re in res}
            mx = metrics(polar(kaf, 1.5e6, "ncrit9", "xlarge"))
            ml = entry["polars"]["ncrit9"]["Re_1.5e6"]
            entry["model_size_check_Re_1.5e6_ncrit9"] = {
                k: {"large": ml[k], "xlarge": mx[k]} for k in ("cl_max", "cd_min", "cm_c4_at_cl_cruise", "l_over_d_max")}
            out[file] = entry
            print(f"polars done: {file}", file=sys.stderr)
    return out


def source_check() -> dict:
    """UIUC ordinates vs exact NACA equations (aerosandbox), Re 1.5e6, ncrit 9."""
    res = {}
    for file, naca in SOURCE_CHECK:
        rows = {}
        for lab, (f, s) in (("uiuc_file", (file, "uiuc")), ("analytic", (naca, "analytic"))):
            _, P = load(f, s)
            kaf, _ = kulfan(lab, P)
            m = metrics(polar(kaf, 1.5e6, "ncrit9"))
            g = geometry(P)
            rows[lab] = {"y_upper_at_x0p0125_percent_c": g["y_upper_at_x0p0125_percent_c"], "t_over_c": g["t_over_c"],
                         **{k: m[k] for k in ("cl_max", "alpha_cl_max_deg", "cd_min", "cm_c4_at_cl_cruise",
                                              "l_over_d_max")}}
        res[file] = rows
    return {"tag": "estimate", "source": NF_URL, **res}


def summary_table(af: dict, rekey: str = "Re_1.5e6") -> list:
    """One flow-style row per airfoil at one Reynolds number (1.5e6: sea-level cruise; 0.8e6: loiter at altitude)."""
    rows = []
    for file, e in af.items():
        c9, c5, tr = (e["polars"][c][rekey] for c in ("ncrit9", "ncrit5", "tripped"))
        g = e["geometry"]

        def ratio(a, b):
            return None if (a is None or b is None) else round(a / b, 2)
        rows.append({
            "airfoil": file, "group": e["group"], "t_over_c": g["t_over_c"], "x_t": g["x_t_max_over_c"],
            "cl_max_n9": c9["cl_max"], "alpha_clmax_n9": c9["alpha_cl_max_deg"], "cl_max_n5": c5["cl_max"],
            "cl_max_trip": tr["cl_max"], "cd_min_n9": c9["cd_min"], "cl_cdmin_n9": c9["cl_at_cd_min"],
            "bucket_n9": c9["drag_bucket_cl_range"], "cm_cruise_n9": c9["cm_c4_at_cl_cruise"],
            "cd_cruise_n9": c9["cd_at_cl_cruise"], "cd_cruise_n5": c5["cd_at_cl_cruise"],
            "cd_cruise_trip": tr["cd_at_cl_cruise"],
            "cd_ratio_trip_n9_cruise": ratio(tr["cd_at_cl_cruise"], c9["cd_at_cl_cruise"]),
            "cd_1p1_n9": c9["cd_at_cl_1p1"], "cd_1p1_trip": tr["cd_at_cl_1p1"],
            "ld_max_n9": c9["l_over_d_max"], "ld_max_trip": tr["l_over_d_max"],
            "endurance_n9": c9["endurance_cl15_over_cd_max"], "endurance_trip": tr["endurance_cl15_over_cd_max"],
            "post_stall_ratio_n9": c9["post_stall_cl_ratio_at_alpha_clmax_plus3deg"],
            "stall_type_gault": e["gault_stall_type_Re_1_3e6"],
        })
    return rows


