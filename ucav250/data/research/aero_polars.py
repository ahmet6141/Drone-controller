#!/usr/bin/env python3
"""YK-250 (ucav250) research phase: airfoil polars (NeuralFoil) and propeller operating-point estimates.

What it does
1. ``--download``: fetches the candidate coordinate files from the UIUC Airfoil Coordinates Database
   (https://m-selig.ae.illinois.edu/ads/coord/), cleans them and writes them in Selig format
   (TE -> upper -> LE -> lower -> TE, first line = original title) to ``ucav250/data/airfoils/<file>.dat``.
   Ordinates are NOT rescaled or smoothed; only the point order (Lednicer -> Selig), junk lines
   ("......", "(0.0016)", Lednicer point counts, the trailing "100.00" line of naca23015.dat) and duplicate
   LE points are fixed.  NACA 4412/4418 (added candidates) are NOT written as files: the UIUC copies have only
   17 points per side and a file named naca44xx.dat would shadow the exact analytic NACA generator in
   ucav250/design/oml.py; they are analysed from analytic ordinates (aerosandbox).
2. Geometry (PCHIP on each surface): t/c and its x/c, camber, thickness at spar stations, section and spar-box
   area (fuel volume), TE thickness, upper ordinate at x/c = 0.0125 (Gault 1957 stall-type parameter).
3. Polars: NeuralFoil (model_size 'large') on the aerosandbox Kulfan (CST) fit of the coordinates, alpha -4..16
   deg in 0.25 deg steps (extended to 22 deg only to locate cl_max), Re 0.8e6 / 1.5e6 / 2.5e6 (tails also 0.5e6):
      ncrit9   n_crit 9, free transition         clean production surface, low-turbulence air
      ncrit5   n_crit 5, free transition         task-defined rough/contaminated case (physically: earlier
                                                  free transition, i.e. higher turbulence / mild roughness)
      tripped  n_crit 9, xtr 0.075 both surfaces  fully turbulent proxy for insects/rain/erosion; same trip
                                                  station as NASA TP-1861 and close to NACA 'standard
                                                  roughness' (0.08c, NACA Rep. 824)
   Cross-checks: 'xlarge' model at Re 1.5e6/ncrit9; UIUC vs analytic ordinates for NACA 4415 and 0010.
4. Propellers: manufacturer performance tables of Mejzlik carbon propellers (thrust/torque/power versus rpm at
   0-50 m/s; Mejzlik 'Propulsion system data' sheets, ISA sea level, measured engine data + Mejzlik propeller
   simulation) are matched to the Limbach L 275 EF WOT torque curve (engine.yaml) to estimate static thrust,
   WOT rpm in flight, and the fixed-pitch partial-throttle efficiency at the cruise thrust required at
   30/35/40 m/s.  All derived operating points are estimates.

Usage (from the repo root)
    python3 ucav250/data/research/aero_polars.py --download          # refresh the .dat files
    python3 ucav250/data/research/aero_polars.py                     # print the generated YAML block
    python3 ucav250/data/research/aero_polars.py --update-yaml       # replace the generated block in aero.yaml

The generated block in aero.yaml sits between the lines
    # >>> BEGIN GENERATED BY aero_polars.py
    # <<< END GENERATED BY aero_polars.py
Everything outside the markers is hand-written research and is never touched by this script.

Environment: numpy 1.26.4, neuralfoil 0.3.3, aerosandbox 4.2.8, scipy, pyyaml (see ucav250/setup_env.sh).
"""
