def _num(tok: str) -> float | None:
    tok = tok.strip().strip("()")
    try:
        return float(tok)
    except ValueError:
        return None


def parse_uiuc(text: str) -> tuple[str, np.ndarray]:
    """Parse a UIUC .dat (Selig or Lednicer, with junk lines) into (title, Selig-ordered points)."""
    lines = text.splitlines()
    title = lines[0].strip()
    pts = []
    for line in lines[1:]:
        tok = line.replace(",", " ").split()
        if len(tok) < 2:
            continue
        x, y = _num(tok[0]), _num(tok[1])
        if x is None or y is None:
            continue                                    # e.g. "0.0000 ......"
        if abs(x) > 1.05 or abs(y) > 0.5:
            continue                                    # Lednicer point-count header, "100.00 0.0000" junk
        pts.append((x, y))
    P = np.array(pts, float)
    if P[0, 0] < 0.5:                                   # Lednicer: upper LE->TE, then lower LE->TE
        i = int(np.where(np.diff(P[:, 0]) < -0.5)[0][0]) + 1
        up, lo = P[:i], P[i:]
        if np.allclose(lo[0], up[0]):
            lo = lo[1:]
        P = np.vstack([up[::-1], lo])
    keep = np.r_[True, np.any(np.abs(np.diff(P, axis=0)) > 1e-9, axis=1)]
    P = P[keep]
    area = 0.5 * np.sum(P[:-1, 0] * P[1:, 1] - P[1:, 0] * P[:-1, 1])
    if area < 0:                                        # Selig order is counter-clockwise (upper surface first)
        P = P[::-1]
    return title, P


def download(files) -> None:
    AIRFOIL_DIR.mkdir(parents=True, exist_ok=True)
    for f in files:
        url = f"{UIUC_URL}{f}.dat"
        with urllib.request.urlopen(url, timeout=60) as r:
            text = r.read().decode("latin-1")
        title, P = parse_uiuc(text)
        body = "\n".join(f" {x:10.7f} {y:10.7f}" for x, y in P)
        (AIRFOIL_DIR / f"{f}.dat").write_text(f"{title}\n{body}\n")
        print(f"downloaded {url} -> {AIRFOIL_DIR / (f + '.dat')} ({len(P)} points)", file=sys.stderr)


def load(file: str, source: str = "uiuc") -> tuple[str, np.ndarray]:
    if source == "analytic":
        import aerosandbox as asb
        af = asb.Airfoil(file).repanel(n_points_per_side=120)
        return f"{file.upper()} (analytic NACA equations, aerosandbox)", np.asarray(af.coordinates, float)
    lines = (AIRFOIL_DIR / f"{file}.dat").read_text().splitlines()
    P = np.array([[float(v) for v in ln.split()[:2]] for ln in lines[1:] if ln.strip()])
    return lines[0].strip(), P


