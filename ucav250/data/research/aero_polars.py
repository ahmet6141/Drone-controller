def to_yaml(data: dict) -> str:
    import yaml

    class Dumper(yaml.SafeDumper):
        pass

    def flow_list(d, v):
        return d.represent_sequence("tag:yaml.org,2002:seq", v, flow_style=not any(isinstance(x, dict) for x in v))

    def maybe_flow_dict(d, v):
        flow = all(not isinstance(x, (dict, list, tuple)) or
                   (isinstance(x, (list, tuple)) and len(x) <= 2 and not any(isinstance(y, (list, dict)) for y in x))
                   for x in v.values())
        return d.represent_mapping("tag:yaml.org,2002:map", v, flow_style=flow)
    Dumper.ignore_aliases = lambda self, data: True
    Dumper.add_representer(list, flow_list)
    Dumper.add_representer(tuple, flow_list)
    Dumper.add_representer(dict, maybe_flow_dict)
    return yaml.dump(data, Dumper=Dumper, sort_keys=False, width=160, allow_unicode=False)


def update_yaml(block: str) -> None:
    text = AERO_YAML.read_text()
    pat = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END), re.S)
    if not pat.search(text):
        raise SystemExit(f"markers not found in {AERO_YAML}")
    AERO_YAML.write_text(pat.sub(lambda _m: f"{BEGIN}\n{block.rstrip()}\n{END}", text))
    print(f"updated generated block in {AERO_YAML}", file=sys.stderr)


