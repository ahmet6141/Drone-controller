def _fit(prop) -> tuple:
    """Cubic CT(J), CQ(J) fit through the upper-rpm rows (>= 55 % of the highest tabulated rpm, J <= 0.85).
    Used only to extrapolate beyond the tabulated rpm range (J-similarity; Re/Mach effects ignored)."""
    D = prop["D_in"] * 0.0254
    rmax = max(r[0] for rows in prop["t"].values() for r in rows)
    J, CT, CQ = [], [], []
    for V, rows in prop["t"].items():
        for rpm, T, Q, _ in rows:
            n = rpm / 60.0
            j = V / (n * D)
            if rpm >= 0.55 * rmax and j <= 0.85:
                J.append(j)
                CT.append(T / (RHO_SL * n * n * D ** 4))
                CQ.append(Q / (RHO_SL * n * n * D ** 5))
    return np.polyfit(J, CT, 3), np.polyfit(J, CQ, 3)


def perf(prop, V: float, rpm: float, rho: float = RHO_SL) -> tuple:
    """(thrust N, torque N m, shaft power W, extrapolated?) at flight speed V and rpm.
    Linear in rpm inside each tabulated speed, linear in V between tabulated speeds, J-similarity fit outside the
    tabulated rpm range; thrust and torque scaled with density (same J, Re effects ignored)."""
    t, D = prop["t"], prop["D_in"] * 0.0254
    Vs = sorted(t)
    va = max(v for v in Vs if v <= V)
    vb = min(v for v in Vs if v >= V)
    if "_fit" not in prop:
        prop["_fit"] = _fit(prop)
    ct, cq = prop["_fit"]
    res, extrap = [], False
    for v in (va, vb):
        rows = np.asarray(t[v], float)
        if rows[0, 0] <= rpm <= rows[-1, 0]:
            res.append((np.interp(rpm, rows[:, 0], rows[:, 1]), np.interp(rpm, rows[:, 0], rows[:, 2])))
        else:
            n = rpm / 60.0
            j = v / (n * D)
            res.append((RHO_SL * n * n * D ** 4 * np.polyval(ct, j), RHO_SL * n * n * D ** 5 * np.polyval(cq, j)))
            extrap = True
    w = 0.0 if vb == va else (V - va) / (vb - va)
    T = ((1 - w) * res[0][0] + w * res[1][0]) * rho / RHO_SL
    Q = ((1 - w) * res[0][1] + w * res[1][1]) * rho / RHO_SL
    return float(T), float(Q), float(Q * 2 * math.pi * rpm / 60.0), extrap


def q_engine(rpm: float, scale: float = 1.0) -> float:
    return scale * float(np.interp(rpm, ENG_RPM, ENG_Q))


def tip_mach(prop, rpm: float, V: float = 0.0) -> float:
    D = prop["D_in"] * 0.0254
    return math.hypot(math.pi * D * rpm / 60.0, V) / A_SL


def thrust_required(V: float, CD0: float = DRAG["CD0"], rho: float = RHO_SL) -> float:
    q = 0.5 * rho * V * V
    W = DRAG["mass_kg"] * G0
    return q * DRAG["S_m2"] * CD0 + W * W / (q * DRAG["S_m2"] * math.pi * DRAG["e"] * DRAG["AR"])


def _solve(f, lo, hi):
    from scipy.optimize import brentq
    flo, fhi = f(lo), f(hi)
    if flo * fhi > 0:
        return None
    return brentq(f, lo, hi, xtol=1.0)


def wot_point(prop, V: float, scale: float = 1.0) -> dict:
    """Fixed-pitch WOT equilibrium: prop torque = engine torque (L 275 EF curve x scale), 4000-7500 rpm."""
    f = lambda n: perf(prop, V, n)[1] - q_engine(n, scale)
    n = _solve(f, ENG_RPM[0], ENG_RPM_MAX)
    if n is None:
        hi = perf(prop, V, ENG_RPM_MAX)[1] < q_engine(ENG_RPM_MAX, scale)
        n = ENG_RPM_MAX if hi else ENG_RPM[0]
        note = "prop underloads the engine: rpm limited at 7500 (governor/throttle)" if hi else \
            "prop overloads the engine: equilibrium below 4000 rpm (outside the published curve)"
    else:
        note = None
    T, Q, P, ex = perf(prop, V, n)
    out = {"rpm": round(n), "thrust_N": round(T), "shaft_power_W": round(P), "tip_mach_helical": round(tip_mach(prop, n, V), 3),
           "extrapolated_beyond_table": ex}
    if V > 0:
        out["efficiency"] = round(T * V / P, 3) if P > 0 else None
    if note:
        out["note"] = note
    return out


def cruise_point(prop, V: float, Treq: float) -> dict:
    f = lambda n: perf(prop, V, n)[0] - Treq
    n = _solve(f, 2500.0, ENG_RPM_MAX)
    if n is None:
        return {"thrust_required_N": round(Treq, 1), "note": "required thrust not reached between 2500 and 7500 rpm"}
    T, Q, P, ex = perf(prop, V, n)
    D = prop["D_in"] * 0.0254
    return {"thrust_required_N": round(Treq, 1), "rpm": round(n), "advance_ratio_J": round(V / (n / 60 * D), 3),
            "shaft_power_W": round(P), "efficiency": round(T * V / P, 3), "tip_mach_helical": round(tip_mach(prop, n, V), 3),
            "throttle_torque_fraction": round(Q / q_engine(n), 2), "extrapolated_beyond_table": ex}


def run_props() -> dict:
    res = {}
    for p in MEJZLIK:
        e = {"label": f"Mejzlik {p['label']}", "diameter_m": round(p["D_in"] * 0.0254, 4),
             "pitch_nominal_m": round(p["P_in"] * 0.0254, 4), "blades": p["blades"], "mass_kg": p["mass_kg"],
             "source": p["url"], "tag": "estimate",
             "basis": "operating points derived from the Mejzlik manufacturer table (tag manufacturer) and the "
                      "L 275 EF datasheet WOT torque curve (tag datasheet)",
             "static_wot_L275EF": wot_point(p, 0.0),
             "static_wot_20kW_class": wot_point(p, 0.0, scale=20000.0 / 18870.0),
             "wot_at_20_m_s": wot_point(p, 20.0), "wot_at_30_m_s": wot_point(p, 30.0),
             "wot_at_40_m_s": wot_point(p, 40.0),
             "cruise_partial_throttle": {f"V_{V:.0f}_m_s": cruise_point(p, V, thrust_required(V)) for V in (30.0, 35.0, 40.0)}}
        res[p["id"]] = e
    # screening: static match 5000-6500 rpm, static tip Mach <= 0.72, WOT rpm at 40 m/s <= 7500 (not limited)
    ok = []
    for pid, e in res.items():
        s, w40 = e["static_wot_L275EF"], e["wot_at_40_m_s"]
        crz = [c.get("efficiency") for c in e["cruise_partial_throttle"].values()]
        if None in crz:
            continue
        c30 = e["cruise_partial_throttle"]["V_30_m_s"]
        passed = (5000 <= s["rpm"] <= 6500 and s["tip_mach_helical"] <= 0.76 and "note" not in s and "note" not in w40
                  and c30.get("rpm", 0) >= 3500)
        e["screen_pass"] = bool(passed)
        e["cruise_efficiency_mean_30_40"] = round(float(np.mean(crz)), 3)
        if passed:
            ok.append((e["cruise_efficiency_mean_30_40"], s["thrust_N"], pid))
    ok.sort(reverse=True)
    return {"screening_rule": "static WOT equilibrium 5000-6500 rpm, static tip Mach <= 0.76, WOT at 40 m/s below "
                              "7500 rpm (prop loads the engine in flight), cruise rpm at 30 m/s >= 3500; ranked by mean "
                              "partial-throttle efficiency at 30/35/40 m/s",
            "ranking": [{"id": pid, "label": res[pid]["label"], "cruise_efficiency_mean_30_40": eff, "static_thrust_N": T}
                        for eff, T, pid in ok],
            "props": res}


