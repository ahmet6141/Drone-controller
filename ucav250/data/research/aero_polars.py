def _surfaces(P):
    ile = int(np.argmin(P[:, 0]))
    up, lo = P[: ile + 1][::-1], P[ile:]
    out = []
    for s in (up, lo):
        s = s[np.argsort(s[:, 0], kind="stable")]
        s = s[np.r_[True, np.diff(s[:, 0]) > 1e-9]]
        out.append(PchipInterpolator(s[:, 0], s[:, 1]))
    return out


def geometry(P: np.ndarray) -> dict:
    """Section geometry on unit chord (LE = min x, chord = max x - min x)."""
    x0, c = P[:, 0].min(), P[:, 0].max() - P[:, 0].min()
    fu, fl = _surfaces((P - [x0, 0.0]) / c)
    xs = 0.5 * (1 - np.cos(np.linspace(0, math.pi, 2001)))
    yu, yl = fu(xs), fl(xs)
    t, cam = yu - yl, 0.5 * (yu + yl)
    it, ic = int(np.argmax(t)), int(np.argmax(np.abs(cam)))

    def box(a, b):
        m = (xs >= a) & (xs <= b)
        return float(np.trapz(t[m], xs[m]))

    def t_at(xc):
        return round(float(fu(xc) - fl(xc)), 4)

    return {
        "t_over_c": round(float(t[it]), 4),
        "x_t_max_over_c": round(float(xs[it]), 3),
        "camber_over_c": round(float(cam[ic]), 4),
        "x_camber_max_over_c": round(float(xs[ic]), 3),
        "t_at_x0p25_over_c": t_at(0.25),
        "t_at_x0p30_over_c": t_at(0.30),
        "t_at_x0p65_over_c": t_at(0.65),
        "t_at_x0p90_over_c": t_at(0.90),
        "te_thickness_over_c": round(float(yu[-1] - yl[-1]), 4),
        "area_over_c2": round(float(np.trapz(t, xs)), 4),
        "box_area_x0p20_x0p65_over_c2": round(box(0.20, 0.65), 4),
        "y_upper_at_x0p0125_percent_c": round(100 * float(fu(0.0125) - 0.0), 2),
        "n_points": int(len(P)),
    }


def gault_stall_type(y125_pct: float) -> str:
    """Stall type from Gault (NACA TN 3963, Fig. 1) for Re ~1-3e6; region boundaries read from the figure
    (+/- 0.2 % c).  The correlation is for smooth models in low turbulence."""
    if y125_pct >= 2.2:
        return "trailing-edge"
    if y125_pct >= 1.75:
        return "combined leading-/trailing-edge (transitional)"
    if y125_pct >= 1.2:
        return "leading-edge"
    return "thin-airfoil"


